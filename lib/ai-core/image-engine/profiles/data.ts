import type { IndustryImageProfile } from "@/lib/ai-core/image-engine/profiles/types";

function u(id: string, w = 1600): string {
  return `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&q=82`;
}

function portrait(id: string): string {
  return u(id, 800);
}

function profile(
  id: string,
  label: string,
  aliases: string[],
  visualStyle: string,
  colorMood: string,
  slots: Partial<IndustryImageProfile["slots"]>,
  subcategories?: string[],
): IndustryImageProfile {
  const hero = slots.hero ?? [u("photo-1497366811353-6870744d04b2")];
  const gallery = slots.gallery ?? hero;
  const about = slots.about ?? gallery.slice(0, 3);
  const features = slots.features ?? gallery.slice(0, 6);
  const team = slots.team ?? [
    portrait("photo-1507003211169-0a1dd7228f2d"),
    portrait("photo-1494790108377-be9c29b29330"),
    portrait("photo-1472099645785-5658abf4ff4e"),
    portrait("photo-1438761681033-6461ffad8d80"),
  ];
  const products = slots.products ?? features;
  const testimonials = slots.testimonials ?? team;
  const backgrounds = slots.backgrounds ?? hero;
  const cta = slots.cta ?? backgrounds.slice(0, 2);

  return {
    id,
    label,
    aliases,
    subcategories,
    visualStyle,
    colorMood,
    slots: { hero, gallery, about, features, team, products, testimonials, backgrounds, cta },
  };
}

